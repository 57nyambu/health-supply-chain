"""Write docs/generated/traceability.md: regulatory requirement → tests that prove it.

Sources: requirement IDs from docs/compliance/KENYA-REGULATORY-REGISTER.md;
markers ``@pytest.mark.req("KE-…")`` in api/ tests and ``req: KE-…`` /
``{ type: 'req', description: 'KE-…' }`` annotations in web/ tests.
Usage: python scripts/ci/traceability.py [--check]
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTER = ROOT / "docs" / "compliance" / "KENYA-REGULATORY-REGISTER.md"
OUTPUT = ROOT / "docs" / "generated" / "traceability.md"
ROW = re.compile(r"^\|\s*(KE-[A-Z]+-\d+)\s*\|\s*(.+?)\s*\|")
PY_MARK = re.compile(r"""(?:mark\.req|req)\(\s*["'](KE-[A-Z]+-\d+)["']""")
PY_TEST = re.compile(r"^\s*(?:async\s+)?def\s+(test_\w+)|^\s*class\s+(Test\w+)", re.MULTILINE)
TS_MARK = re.compile(r"""(?:req:\s*|description:\s*)["'](KE-[A-Z]+-\d+)["']""")


def requirements() -> dict[str, str]:
    reqs = {}
    for line in REGISTER.read_text(encoding="utf-8").splitlines():
        match = ROW.match(line)
        if match:
            text = re.sub(r"\*\*|`", "", match.group(2))
            reqs[match.group(1)] = text if len(text) <= 110 else text[:107].rstrip() + "…"
    return reqs


def _nearest_test(source: str, offset: int) -> str:
    """The test function or class that follows a decorator (or encloses a marker)."""
    following = PY_TEST.search(source, offset)
    if following:
        return following.group(1) or following.group(2)
    return "?"


def evidence() -> dict[str, set[str]]:
    found: dict[str, set[str]] = defaultdict(set)
    for path in sorted((ROOT / "api").rglob("test_*.py")):
        if ".venv" in path.parts:
            continue
        source = path.read_text(encoding="utf-8")
        rel = path.relative_to(ROOT).as_posix()
        for match in PY_MARK.finditer(source):
            if "pytestmark" in source[max(0, match.start() - 200) : match.start()]:
                found[match.group(1)].add(f"`{rel}` (module)")
            else:
                found[match.group(1)].add(f"`{rel}::{_nearest_test(source, match.end())}`")
    web_tests = ROOT / "web" / "tests"
    if web_tests.exists():
        for path in sorted(web_tests.rglob("*.ts")):
            source = path.read_text(encoding="utf-8")
            for match in TS_MARK.finditer(source):
                found[match.group(1)].add(f"`{path.relative_to(ROOT).as_posix()}`")
    return found


def render() -> str:
    reqs = requirements()
    found = evidence()
    covered = sum(1 for rid in reqs if found.get(rid))
    lines = [
        "# Traceability: regulatory requirements → tests",
        "",
        "Generated by `make traceability` from `docs/compliance/KENYA-REGULATORY-REGISTER.md` and the",
        "`req(\"KE-…\")` markers in the test suites. Do not edit by hand.",
        "",
        f"Requirements with automated evidence: **{covered} of {len(reqs)}**.",
        "",
        "| ID | Requirement | Tests |",
        "|---|---|---|",
    ]
    for rid, text in reqs.items():
        tests = "<br>".join(sorted(found.get(rid, []))) or "—"
        lines.append(f"| {rid} | {text.replace('|', '/')} | {tests} |")
    unknown = sorted(set(found) - set(reqs))
    if unknown:
        lines += ["", "Markers that reference IDs missing from the register: " + ", ".join(unknown)]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the committed file is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("docs/generated/traceability.md is stale: run `make traceability`", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
