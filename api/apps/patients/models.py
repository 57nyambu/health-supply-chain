"""Patient registry (DESIGN §5, §6.1, §6.6; KE-DHA-04, KE-DPA-01).

Identifiers, phone numbers, e-mail addresses and next-of-kin details are encrypted at
rest; exact-match search uses HMAC blind indexes. Records are never deleted: duplicates
are merged (maker-checker, reversible) and contacts/identifiers are deactivated.
"""

from typing import Any

from django.contrib.postgres.indexes import GinIndex
from django.db import models
from django.db.models import Q

from apps.core.fields import EncryptedTextField
from apps.core.models import PhiModel


class Patient(PhiModel):
    class Sex(models.TextChoices):
        FEMALE = "female", "Female"
        MALE = "male", "Male"
        INTERSEX = "intersex", "Intersex"
        UNKNOWN = "unknown", "Unknown"

    class Status(models.TextChoices):
        ACTIVE = "active", "Active"
        MERGED = "merged", "Merged into another record"

    mrn = models.CharField("medical record number", max_length=40)
    given_name = models.CharField(max_length=80, blank=True)
    middle_name = models.CharField(max_length=80, blank=True)
    family_name = models.CharField(max_length=80, blank=True)
    search_name = models.CharField(max_length=250, editable=False, db_index=True)
    sex = models.CharField(max_length=10, choices=Sex.choices)
    date_of_birth = models.DateField(null=True, blank=True)
    dob_estimated = models.BooleanField(default=False)
    is_unidentified = models.BooleanField(default=False)
    description = models.CharField(
        max_length=120,
        blank=True,
        help_text="Placeholder for unidentified patients, e.g. Unknown male, approx. 30y",
    )
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.ACTIVE)
    merged_into = models.ForeignKey(
        "self", on_delete=models.PROTECT, null=True, blank=True, related_name="merged_records"
    )

    class Meta:
        ordering = ["family_name", "given_name"]
        constraints = [
            models.UniqueConstraint(fields=["facility", "mrn"], name="patients_mrn_per_facility"),
        ]
        indexes = [
            GinIndex(fields=["search_name"], name="patients_name_trgm", opclasses=["gin_trgm_ops"]),
        ]

    def __str__(self) -> str:
        return f"patient {self.mrn}"

    @property
    def display_name(self) -> str:
        if self.is_unidentified:
            return self.description
        return " ".join(
            part for part in (self.given_name, self.middle_name, self.family_name) if part
        )

    def save(self, *args: Any, **kwargs: Any) -> None:
        self.search_name = " ".join(
            part.lower() for part in (self.given_name, self.middle_name, self.family_name) if part
        )
        super().save(*args, **kwargs)


class PatientIdentifier(PhiModel):
    class Type(models.TextChoices):
        CLIENT_REGISTRY = "cr_id", "HIE Client Registry ID"
        SHA = "sha_number", "SHA number"
        NATIONAL_ID = "national_id", "National ID"
        MAISHA = "maisha_namba", "Maisha Namba"
        ALIEN_ID = "alien_id", "Alien ID"
        REFUGEE_ID = "refugee_id", "Refugee ID"
        PASSPORT = "passport", "Passport"
        BIRTH_CERTIFICATE = "birth_certificate", "Birth certificate"
        BIRTH_NOTIFICATION = "birth_notification", "Birth notification"
        TEMPORARY = "temporary", "Temporary ID (unidentified patient)"

    class Source(models.TextChoices):
        MANUAL = "manual", "Entered by staff"
        CLIENT_REGISTRY = "client_registry", "HIE Client Registry"
        SYSTEM = "system", "Generated by the system"

    patient = models.ForeignKey(Patient, on_delete=models.PROTECT, related_name="identifiers")
    type = models.CharField(max_length=20, choices=Type.choices)
    value = EncryptedTextField()
    value_index = models.CharField(max_length=64, db_index=True)
    issuer = models.CharField(max_length=40, blank=True, help_text="Issuing country for passports")
    source = models.CharField(max_length=20, choices=Source.choices, default=Source.MANUAL)
    verified_at = models.DateTimeField(null=True, blank=True)
    active = models.BooleanField(default=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["facility", "type", "value_index"],
                condition=Q(active=True),
                name="patients_identifier_unique_active",
            ),
        ]

    def __str__(self) -> str:
        return f"{self.type} of patient {self.patient_id}"


class PatientContact(PhiModel):
    class Kind(models.TextChoices):
        PHONE = "phone", "Phone"
        EMAIL = "email", "E-mail"

    patient = models.ForeignKey(Patient, on_delete=models.PROTECT, related_name="contacts")
    kind = models.CharField(max_length=10, choices=Kind.choices)
    value = EncryptedTextField()
    value_index = models.CharField(max_length=64, db_index=True)
    is_primary = models.BooleanField(default=False)
    active = models.BooleanField(default=True)

    def __str__(self) -> str:
        return f"{self.kind} of patient {self.patient_id}"


class NextOfKin(PhiModel):
    patient = models.ForeignKey(Patient, on_delete=models.PROTECT, related_name="next_of_kin")
    name = EncryptedTextField()
    relationship = models.CharField(max_length=40)
    phone = EncryptedTextField(blank=True)
    active = models.BooleanField(default=True)

    def __str__(self) -> str:
        return f"next of kin of patient {self.patient_id}"


class PatientMerge(PhiModel):
    """A merge of ``duplicate`` into ``survivor``; ``moved`` records what changed, so it reverses."""

    class Status(models.TextChoices):
        REQUESTED = "requested", "Waiting for approval"
        MERGED = "merged", "Merged"
        REVERSED = "reversed", "Reversed"

    survivor = models.ForeignKey(Patient, on_delete=models.PROTECT, related_name="merges_kept")
    duplicate = models.ForeignKey(Patient, on_delete=models.PROTECT, related_name="merges_absorbed")
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.REQUESTED)
    reason = models.CharField(max_length=255)
    approval = models.ForeignKey(
        "access.ApprovalRequest", on_delete=models.PROTECT, null=True, related_name="+"
    )
    reversal_approval = models.ForeignKey(
        "access.ApprovalRequest", on_delete=models.PROTECT, null=True, blank=True, related_name="+"
    )
    moved = models.JSONField(default=dict, blank=True)
    merged_at = models.DateTimeField(null=True, blank=True)
    reversed_at = models.DateTimeField(null=True, blank=True)

    def __str__(self) -> str:
        return f"merge {self.duplicate_id} -> {self.survivor_id} ({self.status})"
